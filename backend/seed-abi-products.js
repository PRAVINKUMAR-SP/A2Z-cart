async function runSeed() {
  try {
    const res = await fetch('http://localhost:8085/api/products/batch', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(products)
    });

    if (res.ok) {
      const data = await res.json();
      console.log(`SUCCESS! Saved ${data.length} products to DB under Abi account!`);
    } else {
      const err = await res.text();
      console.error(`Failed to seed products: HTTP ${res.status}`, err);
    }
  } catch (err) {
    console.error('Error connecting to backend:', err.message);
  }
}

